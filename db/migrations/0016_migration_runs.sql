-- 移行を流した記録。
--
-- 移行が済んだ時点から、システムは本番で使われ始める。実際に、投入した翌日に
-- 「過去に蒸留した作業内容」が画面から入力された（タンクの受入が26.3L増えた）。
--
-- ここで危ないのが --reset で、台帳を消してからシートを入れ直す。
-- **画面から入力した分はシートに無いので、消えたまま戻らない。**
-- 手順書は「流し直すときは必ず --reset を付けてください」と書いてあるので、
-- 表記ゆれを1件直すために流し直したときに、黙って失われる。
--
-- 投入直後の行数を控えておき、次に --reset するとき「そのときより増えている＝
-- 画面から入れた行がある」と分かるようにする。行ごとに印を付ける方法もあるが、
-- 台帳12テーブルのうち created_at を持つのは6つだけなので、
-- 行数を控えるほうが取りこぼしがない。

CREATE TABLE migration_runs (
  id           INTEGER PRIMARY KEY,
  finished_at  TEXT NOT NULL DEFAULT (datetime('now')),
  mode         TEXT,                        -- reset / append
  table_counts TEXT NOT NULL                -- 投入直後の行数 {"orders": 156, ...}
);
