-- 段ボール対応表に「どの資材を使うか」を持たせる
--
-- 段ボール7種（300ml12本入り・700ml6本入り など、materials.category = '外箱'）は
-- **資材台帳に1行も記録が無い**。画面に出ている数字は移行したときの初期在庫のまま
-- 止まっていて、実態を表していない。
-- 箱詰めのレシピで減るのは化粧箱・桐箱・プラケース（category = '箱'）という**個装**で、
-- 出荷に使う**外装の段ボールはどこでも減っていない**。
--
-- 繋ぎに足りないのはこの1列だけ。対応表は「商品×本数 → サイズ」しか持たず、
-- どの資材を使うかを持っていない（box_name は自由入力の文字列）。
--
-- **初期値は入れない。** box_name と資材名は表記が違ううえ、
--   300ml一本用   → 300ml1本入り段ボール   … 表記が違う
--   300ml2本用    → **対応する資材が無い**
--   710ml12本海外 → **対応する資材が無い**
--   桐箱一本用    → 個装の桐箱か外装の段ボールか、コードからは決められない
-- という状態で、推測で紐付けると在庫が静かに狂う。
-- 送料設定タブの「段ボール対応表」で1つずつ選んでもらう。
--
-- 設定するまでは推奨が出ないだけで、発送時に手で選べば減算はできる。

ALTER TABLE carton_rules ADD COLUMN material_id INTEGER REFERENCES materials(id);
